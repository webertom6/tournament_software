    s.S.update((state) => {
        state.teams.find((team) => team.id === m.awayTeamId).name = "Shared <name>";
        state.teams.find((team) => team.id === duplicate.id).name = "Shared <name>";
    });
    input = field(s, "ko-away-team", m.id);
    await input.focus(); input.value = "shared";
