    await last.click();
    assert.equal(m.homeTeamId, last.getAttribute("data-team-id"));
    assert.equal(s.alerts.length, 0);
    input = field(s, "phase1-home-team", m.id);
    await input.focus(); input.value = "unfinished";
    await input.dispatch("focusout");
    assert.equal(input.value, input.getAttribute("data-team-name"));
    const reloaded = createSandbox({ page: "admin", initial: { [STATE_KEY]: s.S.exportState() } });
    assert.equal(field(reloaded, "phase1-home-team", m.id).getAttribute("data-team-id"), m.homeTeamId);
