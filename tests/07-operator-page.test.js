    setup(s, 50, 20, { phase1MatchesPerTeam: 3, qualifiedCount: 16 });
    s.A.generatePhase1();
    const m = s.state().phase1.matches[0];
    const other = s.state().phase1.matches[1];
    const target = s.state().teams.find((team) => team.id !== m.homeTeamId && team.id !== m.awayTeamId);
    let input = field(s, "phase1-home-team", m.id);
    assert.equal(input.tagName, "INPUT");
    assert.equal(input.value, s.R.getTeamNameById(s.state(), m.homeTeamId));
    assert.equal(input.getAttribute("aria-expanded"), "false");
    assert.equal(input.closest(".team-picker").querySelector('[role="listbox"]').hidden, true);
    assert.equal(s.document.querySelector(".match-search-label"), null);
    field(s, "phase1-home", other.id).value = "13";
    field(s, "phase1-away", other.id).value = "7";
    field(s, "phase1-home", m.id).value = "99";
    await input.focus();
    assert.equal(input.closest(".team-picker").querySelectorAll('[role="option"]').length, 49);
    const committed = m.homeTeamId;
    input.value = target.name.toLowerCase();
    await input.dispatch("input");
    assert.equal(m.homeTeamId, committed);
    assert.equal(input.closest(".team-picker").querySelectorAll('[role="option"]').length, 1);
    await input.dispatch("keydown", { key: "Enter" });
    assert.equal(m.homeTeamId, target.id);
    assert.equal(m.status, "scheduled");
    assert.equal(m.homeGoals, null);
    assert.equal(field(s, "phase1-home", m.id).value, "");
    assert.equal(field(s, "phase1-home", other.id).value, "13");
    assert.equal(field(s, "phase1-away", other.id).value, "7");
    input = field(s, "phase1-home-team", m.id);
    assert.equal(input.getAttribute("aria-expanded"), "false");
    assert.equal(s.document.activeElement, input);
    const writes = s.storage.writes.length;
    await input.focus();
    input.value = "NoSuchTeam";
    await input.dispatch("input");
    assert.match(input.closest(".team-picker").textContent, /No matching teams/);
    await input.dispatch("keydown", { key: "Enter" });
